"""
Example tests for Feature 2 — Stage 3 revert and virtual patch (task 7.3).

Covers all eight scenarios from the design's Testing Strategy table:

  1. git checkout returns 0  → gerar_virtual_patch is invoked.
  2. git checkout returns ≠0 → gerar_virtual_patch NOT invoked; status = FAILED.
  3. gerar_virtual_patch returns None → status = FAILED; no VIRTUAL_PATCH UPDATE.
  4. validate_virtual_patch receives non-existent file → returns False.
  5. Python file with invalid syntax → py_compile fails → returns False.
  6. PHP file with invalid syntax (mock subprocess.run) → returns False.
  7. Node.js file with invalid syntax (mock subprocess.run) → returns False.
  8. Validation passes → UPDATE contains virtual_patch_path, virtual_patch_data,
     previous_version.

Requirements: 4.2, 4.3, 5.1, 5.5, 7.1–7.7, 8.1–8.5
"""

import os
import sys
import pytest
from unittest.mock import MagicMock, patch, call

import framework
from framework import validate_virtual_patch


# ---------------------------------------------------------------------------
# Helpers / constants
# ---------------------------------------------------------------------------

_PKG = "requests"
_OLD_VER = "2.27.1"
_NEW_VER = "2.31.0"
_ECOSYSTEM = "Python"

# Content long enough to pass the 50-byte size check (> 50 bytes)
_VALID_PATCH_CODE = (
    "# Virtual Patch - Auto-generated by AI Agent\n"
    "# Package: requests\n"
    "# This patch mitigates CVE-2023-32681\n"
    "import warnings\n"
    "warnings.warn('virtual patch active')\n"
)


def _make_patch_data(file_path: str, code: str = _VALID_PATCH_CODE) -> dict:
    """Build a minimal patch_data dict as returned by gerar_virtual_patch()."""
    return {
        "patch_code": code,
        "file_path": file_path,
        "justification": "Virtual patch for test",
    }


# ---------------------------------------------------------------------------
# Scenario 1 — Req 4.2, 4.3
# git checkout returns 0 → gerar_virtual_patch IS invoked
# ---------------------------------------------------------------------------

def test_git_checkout_success_calls_generate_virtual_patch(
    monkeypatch, tmp_patch_dir
):
    """
    WHEN git checkout returns returncode=0 (smoke test path),
    THEN generate_virtual_patch() (which wraps gerar_virtual_patch) is called.

    We test this by patching subprocess.run so that:
      - The package-manager update command returns rc=0
      - run_smoke_test returns False (triggering the revert path)
      - git checkout returns rc=0
    Then we assert generate_virtual_patch was reached by patching it.
    """
    patch_file = str(tmp_patch_dir / "virtual_patches" / "requests_virtual_patch.py")

    # Write a valid patch file to disk so validate_virtual_patch passes later
    os.makedirs(os.path.dirname(patch_file), exist_ok=True)
    with open(patch_file, "w") as f:
        f.write(_VALID_PATCH_CODE)

    generate_called = []

    def fake_generate(cur, pkg, ecosystem, old_ver, target_path):
        generate_called.append(pkg)
        return _make_patch_data(patch_file)

    def fake_run(cmd, **kwargs):
        mock_result = MagicMock()
        if "git" in cmd and "checkout" in cmd:
            mock_result.returncode = 0
            mock_result.stderr = ""
        else:
            # package manager update command
            mock_result.returncode = 0
            mock_result.stderr = ""
        return mock_result

    # Build a mock connection/cursor that returns one approved OPEN row
    mock_cur = MagicMock()
    mock_cur.fetchall.side_effect = [
        [("Python",)],                                             # SELECT DISTINCT ecosystem
        [(1, _PKG, _OLD_VER, _NEW_VER, "approved by AI")],        # SELECT DISTINCT ON package_name
    ]
    mock_cur.fetchone.return_value = None

    mock_conn = MagicMock()
    mock_conn.cursor.return_value = mock_cur

    with (
        patch("framework.subprocess.run", side_effect=fake_run),
        patch("framework.run_smoke_test", return_value=False),
        patch("framework.generate_virtual_patch", side_effect=fake_generate),
        patch("framework.validate_virtual_patch", return_value=True),
        patch("framework.shutil.which", return_value="/usr/bin/pip"),
    ):
        framework.stage3_apply_patches(mock_conn, str(tmp_patch_dir))

    assert generate_called == [_PKG], (
        "generate_virtual_patch must be invoked when git checkout returns 0"
    )


# ---------------------------------------------------------------------------
# Scenario 2 — Req 4.2, 4.3
# git checkout returns ≠0 → gerar_virtual_patch NOT invoked; status = FAILED
# ---------------------------------------------------------------------------

def test_git_checkout_failure_skips_virtual_patch_and_marks_failed(
    monkeypatch, tmp_patch_dir
):
    """
    WHEN git checkout returns returncode != 0,
    THEN generate_virtual_patch is NOT called
    AND the UPDATE sets remediation_status = 'FAILED'.
    """
    generate_called = []

    def fake_generate(*args, **kwargs):
        generate_called.append(True)
        return None

    def fake_run(cmd, **kwargs):
        mock_result = MagicMock()
        if "git" in cmd and "checkout" in cmd:
            mock_result.returncode = 128
            mock_result.stderr = "fatal: pathspec did not match"
        else:
            mock_result.returncode = 0
            mock_result.stderr = ""
        return mock_result

    mock_cur = MagicMock()
    mock_cur.fetchall.side_effect = [
        [("Python",)],
        [(_PKG,)],
    ]
    mock_cur.fetchone.return_value = None

    # Make fetchall return a proper tuple row for the package query
    mock_cur.fetchall.side_effect = [
        [("Python",)],
        [(1, _PKG, _OLD_VER, _NEW_VER, "approved by AI")],
    ]

    mock_conn = MagicMock()
    mock_conn.cursor.return_value = mock_cur

    with (
        patch("framework.subprocess.run", side_effect=fake_run),
        patch("framework.run_smoke_test", return_value=False),
        patch("framework.generate_virtual_patch", side_effect=fake_generate),
        patch("framework.shutil.which", return_value="/usr/bin/pip"),
    ):
        framework.stage3_apply_patches(mock_conn, str(tmp_patch_dir))

    assert generate_called == [], (
        "generate_virtual_patch must NOT be called when git checkout fails"
    )

    # The UPDATE must set remediation_status = 'FAILED'
    executed_sqls = [str(c.args[0]) for c in mock_cur.execute.call_args_list]
    failed_updates = [s for s in executed_sqls if "FAILED" in s]
    assert failed_updates, "At least one UPDATE with FAILED status must be issued"


