def test_validate_virtual_patch_nonexistent_file_returns_false(tmp_path):
    """
    WHEN patch_data["file_path"] points to a file that does not exist,
    THEN validate_virtual_patch returns False.
    """
    patch_data = _make_patch_data(str(tmp_path / "does_not_exist.py"))

    result = validate_virtual_patch(patch_data, "Python")

    assert result is False


