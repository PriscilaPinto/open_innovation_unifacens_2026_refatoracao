def test_validate_virtual_patch_invalid_php_syntax_returns_false(tmp_path):
    """
    WHEN subprocess.run for 'php -l' returns a non-zero returncode,
    THEN validate_virtual_patch returns False.
    """
    # Create a file > 50 bytes so it passes the size check
    php_file = tmp_path / "bad_virtual_patch.php"
    php_file.write_bytes(b"<?php echo 'valid enough content for size check'; ?>" + b"x" * 20)

    patch_data = _make_patch_data(str(php_file))

    mock_result = MagicMock()
    mock_result.returncode = 255
    mock_result.stderr = "PHP Parse error: syntax error"

    with patch("framework.subprocess.run", return_value=mock_result):
        result = validate_virtual_patch(patch_data, "PHP")

    assert result is False


