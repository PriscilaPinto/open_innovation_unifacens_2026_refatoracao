# ---------------------------------------------------------------------------
# Scenario 8 — Req 5.5, 8.1, 8.2, 8.3, 8.4, 8.5
# Validation passes → UPDATE contains virtual_patch_path, virtual_patch_data,
# previous_version
# ---------------------------------------------------------------------------

def test_validate_virtual_patch_success_and_supabase_update(
    monkeypatch, tmp_patch_dir
):
    """
    WHEN validate_virtual_patch returns True,
    THEN the Supabase UPDATE sets:
      - remediation_status = 'VIRTUAL_PATCH'
      - virtual_patch_path  (non-None)
      - virtual_patch_data  (non-None)
      - previous_version    (equals installed_version before update)
    """
    patch_file = str(tmp_patch_dir / "virtual_patches" / f"{_PKG}_virtual_patch.py")
    os.makedirs(os.path.dirname(patch_file), exist_ok=True)
    with open(patch_file, "w") as f:
        f.write(_VALID_PATCH_CODE)

    good_patch_data = _make_patch_data(patch_file)

    def fake_run(cmd, **kwargs):
        r = MagicMock()
        if "git" in cmd and "checkout" in cmd:
            r.returncode = 0
            r.stderr = ""
        else:
            r.returncode = 0
            r.stderr = ""
        return r

    mock_cur = MagicMock()
    mock_cur.fetchall.side_effect = [
        [("Python",)],
        [(1, _PKG, _OLD_VER, _NEW_VER, "approved by AI")],
    ]
    mock_cur.fetchone.return_value = None

    mock_conn = MagicMock()
    mock_conn.cursor.return_value = mock_cur

    with (
        patch("framework.subprocess.run", side_effect=fake_run),
        patch("framework.run_smoke_test", return_value=False),
        patch("framework.generate_virtual_patch", return_value=good_patch_data),
        patch("framework.validate_virtual_patch", return_value=True),
        patch("framework.shutil.which", return_value="/usr/bin/pip"),
    ):
        framework.stage3_apply_patches(mock_conn, str(tmp_patch_dir))

    # Find the VIRTUAL_PATCH UPDATE call among all cursor.execute calls
    virtual_patch_call = None
    for c in mock_cur.execute.call_args_list:
        sql = str(c.args[0])
        if "VIRTUAL_PATCH" in sql:
            virtual_patch_call = c
            break

    assert virtual_patch_call is not None, (
        "An UPDATE with 'VIRTUAL_PATCH' status must be issued"
    )

    # The parameters tuple: (old_ver, patch_path, patch_code, pkg, ecosystem)
    params = virtual_patch_call.args[1]

    assert params[0] == _OLD_VER, (
        f"previous_version must equal old installed version '{_OLD_VER}', got '{params[0]}'"
    )
    assert params[1] == good_patch_data["file_path"], (
        "virtual_patch_path must match patch_data['file_path']"
    )
    assert params[2] == good_patch_data["patch_code"], (
        "virtual_patch_data must match patch_data['patch_code']"
    )
    assert params[1] is not None, "virtual_patch_path must not be None"
    assert params[2] is not None, "virtual_patch_data must not be None"
