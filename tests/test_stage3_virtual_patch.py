# Scenario 3 — Req 5.1
# gerar_virtual_patch returns None → status = FAILED; no VIRTUAL_PATCH UPDATE
# ---------------------------------------------------------------------------

def test_generate_virtual_patch_returns_none_marks_failed(
    monkeypatch, tmp_patch_dir
):
    """
    WHEN generate_virtual_patch() returns None (smoke-test failure path),
    THEN no UPDATE with 'VIRTUAL_PATCH' is issued
    AND the stage returns without raising an exception
    AND total_failed is incremented (verified via the return value of 0 patched packages).

    Note: in the smoke-test path the code increments total_failed directly without
    a separate FAILED UPDATE when patch_data is None — that is the actual implementation
    behaviour (the git-checkout FAILED UPDATE fires only when git checkout itself fails).
    """
    def fake_run(cmd, **kwargs):
        mock_result = MagicMock()
        if "git" in cmd and "checkout" in cmd:
            mock_result.returncode = 0
            mock_result.stderr = ""
        else:
            mock_result.returncode = 0
            mock_result.stderr = ""
        return mock_result

    mock_cur = MagicMock()
    mock_cur.fetchall.side_effect = [
        [("Python",)],
        [(1, _PKG, _OLD_VER, _NEW_VER, "approved by AI")],
    ]
    mock_cur.fetchone.return_value = None

    mock_conn = MagicMock()
    mock_conn.cursor.return_value = mock_cur

    with (
        patch("framework.subprocess.run", side_effect=fake_run),
        patch("framework.run_smoke_test", return_value=False),
        patch("framework.generate_virtual_patch", return_value=None),
        patch("framework.shutil.which", return_value="/usr/bin/pip"),
    ):
        total = framework.stage3_apply_patches(mock_conn, str(tmp_patch_dir))

    executed_sqls = [str(c.args[0]) for c in mock_cur.execute.call_args_list]

    # The essential requirement: no VIRTUAL_PATCH must be persisted
    virtual_patch_updates = [s for s in executed_sqls if "VIRTUAL_PATCH" in s]
    assert not virtual_patch_updates, (
        "No VIRTUAL_PATCH UPDATE must be issued when gerar_virtual_patch returns None"
    )

    # The stage returns 0 successfully remediated/virtual-patched packages
    assert total == 0, (
        "Return value must be 0 when the only package fails (no virtual patch generated)"
    )


