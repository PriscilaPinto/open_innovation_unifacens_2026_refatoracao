# Scenario 5 — Req 7.3, 7.4, 7.5
# Python file with invalid syntax → py_compile fails → returns False
# ---------------------------------------------------------------------------

def test_validate_virtual_patch_invalid_python_syntax_returns_false(tmp_path):
    """
    WHEN the patch file contains invalid Python syntax,
    THEN validate_virtual_patch (using py_compile internally) returns False.
    The file must also be removed from disk on failure.
    """
    # Create a file > 50 bytes but with invalid Python
    invalid_py = tmp_path / "bad_syntax_virtual_patch.py"
    invalid_content = "def broken(:\n    pass\n# " + "x" * 60  # > 50 bytes, bad syntax
    invalid_py.write_text(invalid_content, encoding="utf-8")

    patch_data = _make_patch_data(str(invalid_py))

    result = validate_virtual_patch(patch_data, "Python")

    assert result is False
    # The validator should attempt to remove the invalid file
    assert not invalid_py.exists(), "Invalid syntax file should be removed by the validator"


